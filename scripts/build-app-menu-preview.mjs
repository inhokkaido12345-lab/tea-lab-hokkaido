/** Bundle this isolated demo for file-open review. Production apps never consume the bundle.
 * Regenerate after editing component/demo sources; --check verifies the committed preview.
 */
import fs from 'node:fs';
const root=new URL('../',import.meta.url),read=p=>fs.readFileSync(new URL(p,root),'utf8');
let html=read('prototypes/app-menu/index.html');
for(const [url,path]of [['../../shared/app-menu/app-menu.css','shared/app-menu/app-menu.css'],['demo.css','prototypes/app-menu/demo.css']]){
 const tag='<link rel="stylesheet" href="'+url+'">';if(!html.includes(tag))throw Error('PREVIEW_STYLE_MISSING');html=html.replace(tag,'<style>\n'+read(path)+'\n</style>');
}
for(const [url,path]of [['../../shared/app-menu/catalog.js','shared/app-menu/catalog.js'],['../../shared/app-menu/app-menu.js','shared/app-menu/app-menu.js'],['demo.js','prototypes/app-menu/demo.js']]){
 const tag='<script src="'+url+'" defer></script>';if(!html.includes(tag))throw Error('PREVIEW_SCRIPT_MISSING');html=html.replace(tag,'');
 // Place scripts after the demo DOM. Inline defer does not defer classic scripts.
 html=html.replace('</body>','<script>\n'+read(path)+'\n</script>\n</body>');
}
html='<!-- Generated by scripts/build-app-menu-preview.mjs; edit original files, not this preview. -->\n'+html;
const destination=new URL('prototypes/app-menu/preview.html',root);
if(process.argv.includes('--check')){if(!fs.existsSync(destination)||fs.readFileSync(destination,'utf8')!==html)throw Error('APP_MENU_PREVIEW_STALE');}else fs.writeFileSync(destination,html);
